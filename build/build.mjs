// assets/marp-core.bundle.js を生成するビルドスクリプト。
//
//   npm install && npm run build
//
// 生成物はリポジトリへコミットしておくため、iSlide を使うだけの端末では
// Node.js もビルド環境も不要。実行時に npm / CDN へアクセスすることもない。
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  entryPoints: [path.join(rootDir, 'build/entry.js')],
  outfile: path.join(rootDir, 'assets/marp-core.bundle.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2019'],
  legalComments: 'inline',
  metafile: true,
  banner: {
    js: '/* @marp-team/marp-core bundle for iSlide. Generated by build/build.mjs - do not edit by hand. */',
  },
});

for (const [file, output] of Object.entries(result.metafile.outputs)) {
  console.log(`${file}: ${(output.bytes / 1024).toFixed(0)} KB`);
}
